def fld(fid, type_, label, *who, required=False, **extra):
    row = {"id": fid, "type": type_, "label": label, "required": required, **extra}
    if who:
        row["filled_by"] = list(who)
    return row


def ask(fid, type_, label, required=False, **extra):
    """A field on the public start form. Its label is also the workflow field name, so answers pre-fill."""
    return {"id": fid, "type": type_, "label": label, "required": required, **extra}


